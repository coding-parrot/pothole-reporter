    @PluginMethod
    fun stopDrive(call: PluginCall) {
        val waiter = PendingCancellationWaiter(
            discardData = false,
            onStopped = { summary ->
                call.resolve(summary?.let(::endSummaryObject) ?: JSObject().apply {
                    put("stopped", true)
                    put("discarded", true)
                    put("cancelledStart", true)
                })
            },
            onFailure = { call.reject("Drive start could not be cancelled safely") }
        )
        val pending = synchronized(pendingStartLock) {
            pendingStart?.takeIf { it.gate.requestCancellation(waiter) }
        }
        if (pending != null) {
            queuePendingStartStop(pending)
            return
        }
        val service = DriveForegroundService.activeService
        if (service != null) {
            service.stopDriveSession { summary -> call.resolve(endSummaryObject(summary)) }
        } else {
            call.resolve(JSObject().apply { put("stopped", false) })
        }
    }

    private fun monitorPendingStart(pending: PendingDriveStart) {
        pluginScope.launch {
            val readyDeadline = System.currentTimeMillis() + START_READY_TIMEOUT_MS
            var failure: String? = null
            while (System.currentTimeMillis() < readyDeadline) {
                if (pending.gate.isCancellationRequested()) {
                    failure = "Drive start was cancelled"
                    break
                }
                val completedStart = DriveForegroundService.completedStartSummary(pending.requestId)
                if (completedStart != null) {
                    pending.gate.requestCancellation()
                    failure = completedStart.error ?: "Drive camera failed to start"
                    break
                }
                val status = DriveForegroundService.status()
                if (status.isStopping) {
                    pending.gate.requestCancellation()
                    failure = status.recordingIssue
                        ?: status.status.takeUnless { it.isBlank() || it == "Stopping safely" }
                        ?: "Drive camera failed to start"
                    break
                }
                // Pause is a valid, user-visible terminal state for startup. It turns
                // the camera off deliberately and must not become a 12-second failure.
                if (DriveForegroundService.activeStartRequestId() == pending.requestId &&
                    status.isRunning && (status.cameraActive || status.isPaused || status.captureBlocked)) {
                    if (pending.gate.claimReady()) {
                        synchronized(pendingStartLock) {
                            if (pendingStart === pending) pendingStart = null
                        }
                        pending.call.resolve(statusObject(status))
                        return@launch
                    }
                    failure = "Drive start was cancelled"
                    break
                }
                delay(START_POLL_MS)
            }

            if (failure == null) {
                pending.gate.requestCancellation()
                failure = "Drive camera did not become ready within ${START_READY_TIMEOUT_MS / 1000} seconds"
            }
            // A user Stop queues ACTION_STOP at request time. Timeout/camera-failure
            // cleanup does not enqueue a fresh FGS start; it stops the active/pending
            // component directly and waits for the service's durable Stop callback.
            if (pending.gate.hasStopWaiters()) queuePendingStartStop(pending)
            val discardData = pending.gate.anyWaiter { it.discardData }
            val cancellation = awaitPendingStartCancellation(pending, discardData)
            val waiters = pending.gate.settleCancellation()
            val finalSummary = cancellation.summary?.let { summary ->
                if (waiters.any { it.discardData }) summary.copy(discarded = true) else summary
            }
            synchronized(pendingStartLock) {
                if (pendingStart === pending) pendingStart = null
            }
            pending.call.reject(failure ?: "Drive camera failed to start")
            waiters.forEach { waiter ->
                if (cancellation.stopped) waiter.onStopped(finalSummary)
                else waiter.onFailure()
            }
        }
    }

    private fun queuePendingStartStop(pending: PendingDriveStart) {
        if (!pending.gate.queueStopIntentOnce()) return
        // This request is queued only after ACTION_START was accepted, while the user
        // is still in the foreground. Android delivers the two starts in order, so a
        // delayed ACTION_START cannot survive as a hidden camera session.
        runCatching {
            context.startService(Intent(context, DriveForegroundService::class.java).apply {
                action = DriveForegroundService.ACTION_STOP
                putExtra(DriveForegroundService.EXTRA_STOP_REQUEST_ID, pending.requestId)
                putExtra(
                    DriveForegroundService.EXTRA_STOP_DISCARD_DATA,
                    pending.gate.anyWaiter { it.discardData }
                )
            })
        }
    }

    private data class PendingCancellationResult(
        val stopped: Boolean,
        val summary: DriveEndSummary?
    )

    private suspend fun awaitPendingStartCancellation(
        pending: PendingDriveStart,
        discardData: Boolean
    ): PendingCancellationResult {
        val completion = CompletableDeferred<DriveEndSummary>()
        var callbackRegistered = false
        var lastStatus = DriveForegroundService.status()
        val deadline = System.currentTimeMillis() + START_CANCEL_TIMEOUT_MS
        while (System.currentTimeMillis() < deadline) {
            DriveForegroundService.completedStartSummary(pending.requestId)?.let {
                return PendingCancellationResult(true, it)
            }
            val service = DriveForegroundService.activeService
            lastStatus = DriveForegroundService.status()
            val activeRequest = DriveForegroundService.activeStartRequestId()
            if (!callbackRegistered && activeRequest == pending.requestId && service != null &&
                (lastStatus.isRunning || lastStatus.isStopping)) {
                callbackRegistered = true
                withContext(Dispatchers.Main) {
                    service.stopDriveSession(
                        reason = "Drive start cancelled",
                        discardData = discardData
                    ) { summary -> completion.complete(summary) }
                }
            }
            if (completion.isCompleted) {
                return PendingCancellationResult(true, completion.await())
            }
            if (callbackRegistered && DriveForegroundService.activeService == null) {
                return PendingCancellationResult(true, cancellationSummary(lastStatus, discardData))
            }
            delay(START_POLL_MS)
        }

        // The service never acknowledged the queued cancellation. Force-stop this
        // component, then verify the in-process service reference is gone before any
        // pending Stop call is allowed to resolve.
        withContext(Dispatchers.Main) {
            if (DriveForegroundService.activeStartRequestId() in arrayOf(null, pending.requestId)) {
                context.stopService(Intent(context, DriveForegroundService::class.java))
            }
        }
        val forceDeadline = System.currentTimeMillis() + 2_000L
        while (System.currentTimeMillis() < forceDeadline &&
            DriveForegroundService.activeService != null) {
            delay(START_POLL_MS)
        }
        return PendingCancellationResult(
            stopped = DriveForegroundService.completedStartSummary(pending.requestId) != null ||
                DriveForegroundService.activeStartRequestId() != pending.requestId,
            summary = completion.takeIf { it.isCompleted }?.await()
                ?: DriveForegroundService.completedStartSummary(pending.requestId)
                ?: cancellationSummary(lastStatus, discardData)
        )
    }

