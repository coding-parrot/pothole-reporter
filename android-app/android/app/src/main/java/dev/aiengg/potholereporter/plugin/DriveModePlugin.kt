internal object FootagePathPolicy {
    // Drive IDs are directory names generated by the app. Keep them to one portable,
    // unambiguous path component; dots and separators have no valid use here.
    private val safeSessionId = Regex("[A-Za-z0-9][A-Za-z0-9_-]{0,127}")

    fun sessionDirectory(filesDir: File, sessionId: String): File {
        require(safeSessionId.matches(sessionId)) { "Invalid drive session" }
        val footageRoot = File(filesDir, "footage").canonicalFile
        val target = File(footageRoot, sessionId).canonicalFile
        require(target != footageRoot && target.parentFile == footageRoot) {
            "Invalid drive session"
        }
        return target
    }

    fun segmentFile(sessionDirectory: File, storedPath: String): File {
        val canonicalSession = sessionDirectory.canonicalFile
        val target = File(storedPath).canonicalFile
        require(target != canonicalSession && target.parentFile == canonicalSession) {
            "Stored footage path is outside this drive"
        }
        return target
    }

    fun keyframeFile(sessionDirectory: File, storedPath: String): File {
        val canonicalSession = sessionDirectory.canonicalFile
        val keyframeDirectory = File(canonicalSession, "keyframes").canonicalFile
        require(keyframeDirectory.parentFile == canonicalSession) { "Invalid keyframe directory" }
        val target = File(storedPath).canonicalFile
        require(target != keyframeDirectory && target.parentFile == keyframeDirectory) {
            "Stored keyframe path is outside this drive"
        }
        return target
    }
}

internal class PendingStartGate<T> {
    private var settled = false
    private var cancellationRequested = false
    private var startRequestAccepted = false
    private var stopIntentQueued = false
    private val stopWaiters = mutableListOf<T>()

    @Synchronized
    fun requestCancellation(stopWaiter: T? = null): Boolean {
        if (settled) return false
        cancellationRequested = true
        if (stopWaiter != null) stopWaiters.add(stopWaiter)
        return true
    }

    @Synchronized
    fun isCancellationRequested(): Boolean = cancellationRequested

    @Synchronized
    fun hasStopWaiters(): Boolean = stopWaiters.isNotEmpty()

    @Synchronized
    fun anyWaiter(predicate: (T) -> Boolean): Boolean = stopWaiters.any(predicate)

    @Synchronized
    fun claimReady(): Boolean {
        if (settled || cancellationRequested) return false
        settled = true
        return true
    }

    @Synchronized
    fun markStartRequestAccepted(): Boolean {
        startRequestAccepted = true
        return cancellationRequested
    }

    @Synchronized
    fun queueStopIntentOnce(): Boolean {
        if (!startRequestAccepted || stopIntentQueued) return false
        stopIntentQueued = true
        return true
    }

    @Synchronized
    fun settleCancellation(): List<T> {
        if (settled) return emptyList()
        settled = true
        return stopWaiters.toList().also { stopWaiters.clear() }
    }
}

