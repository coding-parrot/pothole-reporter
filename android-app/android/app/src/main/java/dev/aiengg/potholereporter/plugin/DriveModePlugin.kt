    @PluginMethod
    fun startDrive(call: PluginCall) {
        val apiKey = call.getString("apiKey") ?: ""
        val model = call.getString("model") ?: "gpt-5-mini"
        val detail = call.getString("detail") ?: "high"
        val language = call.getString("language") ?: "en"
        val debug = call.getBoolean("debug") ?: false
        val recordVideo = call.getBoolean("recordVideo") ?: false
        val maxDurationMinutes = (call.getInt("maxDurationMinutes")
            ?: DriveSessionLimitPolicy.DEFAULT_LIMIT_MINUTES).coerceIn(
            DriveSessionLimitPolicy.MIN_LIMIT_MINUTES,
            DriveSessionLimitPolicy.MAX_LIMIT_MINUTES
        )

        if (!hasDrivePermissions()) {
            call.reject("Camera and location permission are required before Drive Mode can start")
            return
        }
        if (!hasNotificationPermission()) {
            call.reject("Enable Pothole Reporter notifications in Android Settings so camera use is always visible")
            return
        }
        if (apiKey.isBlank()) {
            call.reject("An OpenAI API key is required")
            return
        }
        val existing = DriveForegroundService.status()
        if (existing.isRunning) {
            // This call did not create that session. During a phone/video-call camera
            // interruption it is legitimately running with cameraActive=false; return
            // the truthful status without timing out or stopping somebody else's drive.
            call.resolve(statusObject(existing))
            return
        }
        if (existing.isStopping) {
            call.reject("The previous drive is still stopping safely")
            return
        }
        val pending = PendingDriveStart(call)
        val accepted = synchronized(pendingStartLock) {
            if (pendingStart != null) false else {
                pendingStart = pending
                true
            }
        }
        if (!accepted) {
            call.reject("Drive Mode is already starting")
            return
        }
        val context = context
        val serviceIntent = Intent(context, DriveForegroundService::class.java).apply {
            action = DriveForegroundService.ACTION_START
            putExtra(DriveForegroundService.EXTRA_API_KEY, apiKey)
            putExtra(DriveForegroundService.EXTRA_MODEL, model)
            putExtra(DriveForegroundService.EXTRA_DETAIL, detail)
            putExtra(DriveForegroundService.EXTRA_LANGUAGE, language)
            putExtra(DriveForegroundService.EXTRA_DEBUG, debug)
            putExtra(DriveForegroundService.EXTRA_RECORD_VIDEO, recordVideo)
            putExtra(DriveForegroundService.EXTRA_MAX_DRIVE_MINUTES, maxDurationMinutes)
            putExtra(DriveForegroundService.EXTRA_START_REQUEST_ID, pending.requestId)
        }

        try {
            ContextCompat.startForegroundService(context, serviceIntent)
        } catch (error: Exception) {
            synchronized(pendingStartLock) {
                if (pendingStart === pending) pendingStart = null
            }
            val waiters = pending.gate.settleCancellation()
            call.reject("Drive Mode could not start: ${error.message ?: "service start failed"}")
            waiters.forEach { it.onStopped(null) }
            return
        }
        if (pending.gate.markStartRequestAccepted()) queuePendingStartStop(pending)
        monitorPendingStart(pending)
    }

